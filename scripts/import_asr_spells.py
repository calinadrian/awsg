"""Import extracted ASR definition data; never runs or modifies the original game.

Usage: python3.12 scripts/import_asr_spells.py original-tables.json
The reference uses 120-byte spell records at RVA 0x6fea020 (0.124.5).
"""
import json
from pathlib import Path
import re
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "crates/benilla-app/src/survivors"
ALIASES = {"demo_shout": "demoralizing_shout", "sw_pain": "shadow_word_pain", "pw_shield": "power_word_shield"}
# Fork class pools replace these attacks with self-healing abilities.
HEAL_REPLACEMENTS = {
    "explosive_trap": ("mending", 136, 3),
    "gouge": ("recuperate", 746, 0),
    "blast_wave": ("evocation", 12051, 6),
}


def generate(reference):
    rows = reference["abilities"]
    lines = ["// Definition data from original ASR 0.124.5, spell table RVA 0x6fea020.",
             "// Generated by scripts/import_asr_spells.py, including fork self-heal replacements.",
             f"// Reference executable SHA-256: {reference['sha256']}",
             "pub(crate) static ABILITIES: &[AbilityDef] = &["]
    axes = ["// Original spell upgrade eligibility, generated alongside spell_data.rs.",
            "use super::rewards::Upgrade;", "pub(super) fn axes(key: &str) -> &'static [Upgrade] {",
            "    use Upgrade::*;", "    match key {"]
    for row in rows:
        key = ALIASES.get(row["key"], row["key"])
        b = bytes.fromhex(row["tail"])
        spell, damage, cd, reach, radius, count, duration, ticks, speed, sub, effect, value, seconds, school, native = struct.unpack("<IffffIfIfIIffBB2x", b)
        fmt = lambda n: repr(round(n, 6))
        kind = {0: "Bolt", 1: "Missiles", 2: "Nova", 3: "Ground", 4: "Chain", 5: "Melee", 6: "Dot", 7: "Execute", 8: "Cone", 9: "Buff", 10: "Totem", 11: "Passive"}[native]
        if native == 3 and reach == 0:
            kind = "GroundSelf"
        if native == 9:
            kind = {6: "Heal", 7: "Shield", 12: "Immune", 13: "Thorns"}.get(effect, "Buff")
            damage = value
        if key == "lightwell":
            kind = "Totem"
        fields = dict(damage=fmt(damage), cooldown=fmt(cd), range=fmt(reach), radius=fmt(radius),
                      count=str(count), duration=fmt(duration), ticks=str(ticks), speed=fmt(speed),
                      school=str(school), native_kind=str(native), self_effect=str(effect if native == 9 else 0))
        if native == 6:
            fields["damage"] = "0.0"
            fields["dot"] = fmt(damage / duration)
        if native != 9:
            eff = {1: f"Slow({fmt(1-value)}, {fmt(seconds)})", 2: f"Root({fmt(value)})",
                   3: f"Stun({fmt(value)})", 4: f"Fear({fmt(value)})", 5: f"Drain({fmt(value)})",
                   6: f"Heal({fmt(value)})", 7: f"Shield({fmt(value)})", 11: f"Weaken({fmt(1-value)}, {fmt(seconds)})"}.get(effect)
            if eff:
                fields["effect"] = "Effect::" + eff
                fields["mark"] = str(spell)
        if kind == "Totem":
            fields["totem"] = {"searing_totem": "(4589, 3606)", "magma_totem": "(4588, 8187)", "lightwell": "(2030, 724)"}[key]
        if key in ("blizzard", "hurricane"):
            fields["overhead"] = "true"
        replacement = HEAL_REPLACEMENTS.get(key)
        if replacement:
            key, spell, school = replacement
            kind = "Heal"
            fields = dict(damage="0.3", cooldown="12.0", range="0.0", radius="0.0",
                          count="0", duration="6.0", ticks="0", speed="0.0",
                          school=str(school), native_kind="9", self_effect="6")
        lines.append(f'    ability!("{key}", {spell}, {kind} {{ ' + ", ".join(f"{k}: {v}" for k, v in fields.items()) + " }),")
        tags = "Power, Cooldown" if replacement else ", ".join(["Power", "Cooldown", "Targets", "Area", "Duration"][tag] for tag in row["tags"])
        axes.append(f'        "{key}" => &[{tags}],')
    lines.append("];")
    axes.extend(['        _ => &[Power, Cooldown],', "    }", "}"])
    (DEST / "spell_data.rs").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    (DEST / "reward_axes.rs").write_text("\n".join(axes) + "\n", encoding="utf-8", newline="\n")
    # Class record +64 is the starting spell; in this reference it is the first pool key.
    # Keep model/weapon choices and the unrelated map/enemy data in data.rs intact.
    path = DEST / "data.rs"
    source = path.read_text(encoding="utf-8")
    for cls in reference["classes"]:
        pool = [ALIASES.get(key, key) for key in cls["pool"]]
        pool = [HEAL_REPLACEMENTS[key][0] if key in HEAL_REPLACEMENTS else key for key in pool]
        pattern = (r'(name: "' + re.escape(cls["name"]) +
                   r'",[\s\S]*?start: ")[^"]+("[\s\S]*?pool: &\[)[\s\S]*?(\],)')
        source = re.sub(pattern, lambda m: m[1] + pool[0] + m[2] + "\n" +
                        "".join(f'            "{key}",\n' for key in pool) +
                        "        " + m[3], source, count=1)
    path.write_text(source, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    generate(json.loads(Path(sys.argv[1]).read_text(encoding="utf-8")))
